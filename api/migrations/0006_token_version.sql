-- 0006_token_version.sql — номер «поколения» входов у каждого человека (проверка 16.11).
--
-- Сессия Таски — токен JWT на 90 дней, который сам продлевается при каждом открытии приложения.
-- Раньше сервер сверял только подпись токена, поэтому смена пароля, выключение сотрудника бегунком
-- в «Команде» и закрытие старого общего пароля 123456 НЕ выгоняли тех, кто уже вошёл.
-- Теперь в токене лежит номер поколения (tv), а сервер на каждом запросе сверяет его с этим столбцом.
-- Сменили пароль или выключили человека — номер растёт на 1, и все прежние входы под этим логином
-- перестают действовать (свой текущий вход при смене своего же пароля сервер тут же выдаёт заново).
--
-- Миграция только ДОБАВЛЯЕТ столбец со значением 0. Старые токены без tv считаются поколением 0,
-- поэтому после обновления никого не выкинет — пока у человека не сменят пароль или не выключат его.
alter table users add column if not exists token_version integer not null default 0;
