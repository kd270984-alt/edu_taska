// Старый .env мог быть скопирован из примера, где комментарий стоял в той же строке: «AGENT_MODEL=   # пусто…».
// Docker Compose читает такой комментарий как значение — бот получил бы модель «# пусто…» или «ключ» из текста.
// Поэтому значение, которое начинается с «#», считаем пустым. Модуль импортируется первым — до чтения переменных.
for (const [k, v] of Object.entries(process.env)) {
  if (typeof v === 'string' && v.trim().startsWith('#')) process.env[k] = '';
}
export {};
